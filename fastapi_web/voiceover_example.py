def update_voiceover_status(voiceover_id: str, status: str, error_message: str = None):
    """
    Update the status of a voiceover (useful for tracking processing status)
    
    Args:
        voiceover_id: ID of the voiceover to update
        status: New status ("processing", "completed", "failed")
        error_message: Error message if status is "failed"
    """
    
    with Session(engine) as session:
        statement = select(GeneratedVoiceover).where(GeneratedVoiceover.id == voiceover_id)
        voiceover = session.exec(statement).first()
        
        if voiceover:
            voiceover.status = status
            voiceover.updated_at = datetime.now()
            
            if error_message:
                voiceover.error_message = error_message
                
            session.add(voiceover)
            session.commit()

