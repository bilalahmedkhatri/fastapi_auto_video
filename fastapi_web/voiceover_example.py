"""
Example usage of the GeneratedVoiceover table for saving voiceover URLs
"""

from models.db_models import GeneratedVoiceover, get_session
from sqlmodel import Session, select
from datetime import datetime
import json

def save_voiceover_to_db(
    user_id: str,
    voice_id: str,
    voice_name: str,
    text_content: str,
    filename: str,
    file_url: str,
    script_id: str = None,
    video_id: str = None,
    speed: float = 1.0,
    pitch: float = 1.0,
    volume: float = 0.8,
    tone: str = None,
    file_size: int = None,
    duration_seconds: float = None,
    ai_provider: str = None,
    ai_model: str = None
) -> GeneratedVoiceover:
    """
    Save a generated voiceover to the database
    
    Args:
        user_id: ID of the user who generated the voiceover
        voice_id: ID of the voice used (from SelectAIVoices table)
        voice_name: Human-readable name of the voice
        text_content: The text that was converted to speech
        filename: The actual filename (e.g., "voiceover_demo-script-123_1757707084.wav")
        file_url: Full URL to access the file (e.g., "/api/audio/voiceover_demo-script-123_1757707084.wav")
        script_id: Optional reference to ScriptGeneration table
        video_id: Optional reference to Video table
        speed: Playback speed (default: 1.0)
        pitch: Voice pitch (default: 1.0)
        volume: Audio volume (default: 0.8)
        tone: Voice tone setting
        file_size: File size in bytes
        duration_seconds: Audio duration in seconds
        ai_provider: Provider used (e.g., "replicate", "elevenlabs", "openai")
        ai_model: Specific model used
    
    Returns:
        GeneratedVoiceover: The created voiceover record
    """
    
    with Session(engine) as session:
        voiceover = GeneratedVoiceover(
            user_id=user_id,
            script_id=script_id,
            video_id=video_id,
            voice_id=voice_id,
            voice_name=voice_name,
            text_content=text_content,
            speed=speed,
            pitch=pitch,
            volume=volume,
            tone=tone,
            filename=filename,
            file_url=file_url,
            file_size=file_size,
            duration_seconds=duration_seconds,
            ai_provider=ai_provider,
            ai_model=ai_model,
            status="completed"
        )
        
        session.add(voiceover)
        session.commit()
        session.refresh(voiceover)
        
        return voiceover

def get_user_voiceovers(user_id: str) -> list[GeneratedVoiceover]:
    """
    Get all voiceovers generated by a specific user
    
    Args:
        user_id: ID of the user
        
    Returns:
        List of GeneratedVoiceover records
    """
    
    with Session(engine) as session:
        statement = select(GeneratedVoiceover).where(GeneratedVoiceover.user_id == user_id)
        voiceovers = session.exec(statement).all()
        return voiceovers

